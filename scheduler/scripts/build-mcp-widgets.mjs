import { copyFile, mkdir, writeFile, readFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import tailwind from "@tailwindcss/postcss";
import { build } from "esbuild";
import postcss from "postcss";

const { format } = await import("prettier");

const schedulerRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outdir = path.resolve(schedulerRoot, "public/mcp-widgets");
const generatedAssetsPath = path.resolve(schedulerRoot, "lib/mcp/ui/widget-assets.ts");
const entryPoints = {
  workspace: path.resolve(schedulerRoot, "mcp-ui/extensions/workspace.tsx"),
  "post-editor": path.resolve(schedulerRoot, "mcp-ui/extensions/post-editor.tsx"),
  schedule: path.resolve(schedulerRoot, "mcp-ui/schedule.tsx"),
  "post-preview": path.resolve(schedulerRoot, "mcp-ui/post-preview.tsx"),
};

await mkdir(outdir, { recursive: true });
await Promise.all(
  ["Inter-OFL.txt", "JetBrains-Mono-OFL.txt"].map((name) =>
    copyFile(path.resolve(schedulerRoot, "mcp-ui/fonts", name), path.join(outdir, name)),
  ),
);
// Keep previous immutable assets when building into an existing deployment artifact.
const result = await build({
  plugins: [
    {
      name: "shared-design-system",
      setup(build) {
        build.onResolve(
          { filter: /^(next(?:\/|$)|@\/hooks\/|@\/lib\/(?:config|api|auth|mcp))/ },
          ({ path: imported, importer }) => {
            throw new Error(`Widget UI must not import application services: ${imported} from ${importer}`);
          },
        );
        build.onLoad({ filter: /design-system\.css$/ }, async ({ path: cssPath }) => {
          const output = await postcss([tailwind()]).process(await readFile(cssPath, "utf8"), { from: cssPath });
          return { contents: output.css, loader: "css", resolveDir: path.dirname(cssPath) };
        });
      },
    },
  ],
  entryPoints,
  bundle: true,
  entryNames: "[name]-[hash]",
  assetNames: "[name]-[hash]",
  outdir,
  format: "esm",
  platform: "browser",
  loader: { ".woff2": "file" },
  target: "es2022",
  jsx: "automatic",
  sourcemap: false,
  minify: true,
  legalComments: "none",
  logLevel: "info",
  metafile: true,
});

const outputEntries = Object.entries(result.metafile.outputs);
const widgetAssets = Object.fromEntries(
  Object.entries(entryPoints).map(([name, entryPoint]) => {
    const scriptOutput = outputEntries.find(
      ([filename, metadata]) => filename.endsWith(".js") && path.resolve(metadata.entryPoint || "") === entryPoint,
    );
    const script = scriptOutput?.[0];
    const stylesheet = scriptOutput?.[1].cssBundle;

    if (!script || !stylesheet) {
      throw new Error(`Missing JavaScript or CSS output for ${name}`);
    }

    return [
      name,
      {
        script: path.basename(script),
        stylesheet: path.basename(stylesheet),
      },
    ];
  }),
);

const generatedModule = `// Generated by scripts/build-mcp-widgets.mjs. Do not edit manually.
export const WIDGET_ASSETS = ${JSON.stringify(widgetAssets, null, 2)} as const;

export type WidgetName = keyof typeof WIDGET_ASSETS;
`;

await writeFile(generatedAssetsPath, await format(generatedModule, { parser: "typescript" }));
